    fun allProfiles(customEntities: List<CustomDjProfileEntity>): List<DjProfile> {
        return BUILT_IN_PROFILES + customEntities.map { it.toDomain() }
    }

    fun findProfile(id: String, customEntities: List<CustomDjProfileEntity> = emptyList()): DjProfile {
        return allProfiles(customEntities).firstOrNull { it.id == id } ?: BUILT_IN_PROFILES.first()
    }

    fun applyProfile(base: AutomixConfig, profile: DjProfile): AutomixConfig {
        return base.copy(
            activeProfileId = profile.id,
            mode = profile.mixMode,
            bpmMin = profile.bpmMin,
            bpmMax = profile.bpmMax,
            strictGenreMatching = profile.strictGenreMatching,
            harmonicMixLevel = profile.harmonicMixLevel,
            energyProgression = profile.energyProgression,
            transitionStyle = profile.transitionStyle,
            transitionDurationSec = profile.transitionDurationSec,
            keyLockEnabled = profile.keyLockEnabled,
            phraseMatchEnabled = profile.phraseMatchEnabled,
            bpmWeight = profile.bpmWeight,
            harmonicWeight = profile.harmonicWeight,
            energyWeight = profile.energyWeight,
            genreWeight = profile.genreWeight,
            openFormatBridging = profile.openFormatBridging,
            genrePreference = if (profile.preferredGenres.size == 1) profile.preferredGenres.first() else "All Genres",
        )
    }

    fun CustomDjProfileEntity.toDomain(): DjProfile = DjProfile(
        id = id,
        name = name,
        description = description,
        isBuiltIn = false,
        mixMode = runCatching { MixMode.valueOf(mixMode) }.getOrDefault(MixMode.SMART),
        bpmMin = bpmMin,
        bpmMax = bpmMax,
        preferredGenres = preferredGenresCsv.split(",").map { it.trim() }.filter { it.isNotEmpty() },
        strictGenreMatching = strictGenreMatching,
        harmonicMixLevel = runCatching { HarmonicMixLevel.valueOf(harmonicMixLevel) }.getOrDefault(HarmonicMixLevel.BALANCED),
        energyProgression = runCatching { EnergyProgression.valueOf(energyProgression) }.getOrDefault(EnergyProgression.STEADY),
        transitionStyle = runCatching { TransitionStyle.valueOf(transitionStyle) }.getOrDefault(TransitionStyle.SMOOTH_FADE),
        transitionDurationSec = transitionDurationSec,
        keyLockEnabled = keyLockEnabled,
        phraseMatchEnabled = phraseMatchEnabled,
        bpmWeight = bpmWeight,
        harmonicWeight = harmonicWeight,
        energyWeight = energyWeight,
        genreWeight = genreWeight,
        openFormatBridging = openFormatBridging,
    )

    fun DjProfile.toEntity(): CustomDjProfileEntity = CustomDjProfileEntity(
        id = id,
        name = name,
        description = description,
        mixMode = mixMode.name,
        bpmMin = bpmMin,
        bpmMax = bpmMax,
        preferredGenresCsv = preferredGenres.joinToString(","),
        strictGenreMatching = strictGenreMatching,
        harmonicMixLevel = harmonicMixLevel.name,
        energyProgression = energyProgression.name,
        transitionStyle = transitionStyle.name,
        transitionDurationSec = transitionDurationSec,
        keyLockEnabled = keyLockEnabled,
        phraseMatchEnabled = phraseMatchEnabled,
        bpmWeight = bpmWeight,
        harmonicWeight = harmonicWeight,
        energyWeight = energyWeight,
        genreWeight = genreWeight,
        openFormatBridging = openFormatBridging,
    )
